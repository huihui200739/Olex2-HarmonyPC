#!/usr/bin/env python3
"""Generate explicitly synthetic, asymmetric PNGs for original UI texture loading."""
import argparse
import hashlib
import json
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def chunk(kind, payload):
    return struct.pack('>I', len(payload)) + kind + payload + struct.pack('>I', zlib.crc32(kind + payload) & 0xffffffff)

def png(width, rgb):
    rows = b''.join(b'\x00' + rgb[y * width * 3:(y + 1) * width * 3] for y in range(width))
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, width, 8, 2, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(rows, 9)) + chunk(b'IEND', b''))

def render():
    rows = []
    arrays = []
    descriptors = []
    for generation in ('a', 'b'):
        for index, name in enumerate(('LockedAtoms', 'ConstrainedAtoms')):
            width = (2, 4)[index if generation == 'a' else 1 - index]
            # Non-symmetric colors distinguish x/y transposition and replacement.
            rgb = bytes((31 + 47 * x + 19 * y + 53 * c + 23 * index + (61 if generation == 'b' else 0)) % 256
                        for y in range(width) for x in range(width) for c in range(3))
            encoded = png(width, rgb)
            stem = f'fixture_{generation}_{index}'
            for suffix, data in (('png', encoded), ('rgb', rgb)):
                arrays.append(f'inline constexpr unsigned char {stem}_{suffix}[] = {{' + ','.join(map(str, data)) + '};')
            rows.append(dict(generation=generation, name=name, width=width, height=width,
                             rgb=list(rgb), png_bytes=len(encoded), png_sha256=hashlib.sha256(encoded).hexdigest()))
            descriptors.append('  {"' + name + '","' + generation + '",' + str(width) + ',' + stem + '_png,sizeof(' + stem + '_png),' + stem + '_rgb},')
    header = ('#pragma once\n#include <cstddef>\nnamespace olex2::harmony {\n'
              '// Explicitly synthetic colors only; generated by generate-texture-load-fixtures.py.\n'
              'struct OriginalTextureLoadFixture { const char* name; const char* generation; unsigned width; '
              'const unsigned char* png; std::size_t pngSize; const unsigned char* rgb; };\n'
              + '\n'.join(arrays) + '\ninline constexpr OriginalTextureLoadFixture OriginalTextureLoadFixtures[] = {\n'
              + '\n'.join(descriptors) + '\n};\n}\n')
    reference = dict(schema=1, scope='isolated synthetic color PNG inputs; not runtime or GPU observations', fixtures=rows)
    return header, json.dumps(reference, indent=2) + '\n'

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    header, reference = render()
    pairs = [(ROOT/'experiments/gx-texture-load/native/original_texture_load_fixtures.h', header),
             (ROOT/'experiments/gx-texture-load/synthetic-fixtures.json', reference)]
    for path, text in pairs:
        if a.check:
            if path.read_text() != text:
                raise ValueError('Generated fixture differs: ' + str(path))
        else:
            path.write_text(text)
    print('PASS exact synthetic fixture generation' if a.check else 'Generated four synthetic color PNG references')

if __name__ == '__main__':
    main()
